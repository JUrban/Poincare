(* Unit pc_rfa_talg: the bilinear tensor algebra of the Ricci flow analysis  *)
(* layer: inner products and rough Laplacians of (0,k)-tensor fields on open *)
(* sets of real^N, the generators ltprod, ltperm, ltcontr and the class      *)
(* lbilin of bilinear contraction operations with its norm bound,            *)
(* tensoriality, smoothness and Leibniz rule.  Builds on pc_lrg_evol.        *)
(* ========================================================================= *)

needs "src/pc_lrg_evol.ml";;

prioritize_real();;
type_invention_error := true;;

(* ------------------------------------------------------------------------- *)
(* Inner product of (0,k)-tensors at y with respect to G(y); by              *)
(* definition ltnorm2 k G T y = ltinner k G T T y.                           *)
(* ------------------------------------------------------------------------- *)

let ltinner = new_definition
 `ltinner k (G:real^N->real^N^N) (tf:real^N->(num->real^N)->real)
          (tg:real^N->(num->real^N)->real) (y:real^N) =
    sum (index_tuples k (:N))
     (\i. sum (index_tuples k (:N))
           (\j. tf y (\m. basis(i m)) * tg y (\m. basis(j m)) *
                product(1..k) (\m. matrix_inv(G y)$(i m)$(j m))))`;;

(* ------------------------------------------------------------------------- *)
(* Rough Laplacian of a (0,k)-tensor field: the G-trace of the two           *)
(* derivative slots k+1, k+2 of nabla^2 T (for k = 0 it is llap).            *)
(* ------------------------------------------------------------------------- *)

let ltlap = new_definition
 `ltlap k (G:real^N->real^N^N) (tf:real^N->(num->real^N)->real) (y:real^N)
        (u:num->real^N) =
    sum(1..dimindex(:N))
     (\a. sum(1..dimindex(:N))
       (\b. matrix_inv(G y)$a$b *
            lnabla_iter k 2 G tf y
              (\m. if m = k + 1 then basis a else if m = k + 2 then basis b
                   else u m)))`;;

(* ------------------------------------------------------------------------- *)
(* The three generators of the bilinear tensor algebra: tensor product       *)
(* (slots 1..p for S, p+1..p+q for T), slot permutation, and the metric      *)
(* contraction of the FIRST two slots with the remaining slots shifted down  *)
(* (the convention of LRG_LNABLA_CONTRACT in pc_lrg_evol).                   *)
(* ------------------------------------------------------------------------- *)

let ltprod = new_definition
 `ltprod p (tf:real^N->(num->real^N)->real) (tg:real^N->(num->real^N)->real) =
    \y u. tf y u * tg y (\m. u(m + p))`;;

let ltperm = new_definition
 `ltperm (s:num->num) (tf:real^N->(num->real^N)->real) =
    \y u. tf y (\m. u(s m))`;;

let ltcontr = new_definition
 `ltcontr (G:real^N->real^N^N) (tf:real^N->(num->real^N)->real) =
    \y u. sum(1..dimindex(:N))
           (\a. sum(1..dimindex(:N))
             (\b. matrix_inv(G y)$a$b *
                  tf y (\m. if m = 1 then basis a else if m = 2 then basis b
                           else u(m - 2))))`;;

(* ------------------------------------------------------------------------- *)
(* The class lbilin k p q B of bilinear contraction operations taking a      *)
(* (0,p)- and a (0,q)-tensor to a (0,k)-tensor (S x T of the Ricci flow      *)
(* literature): generated by ltprod, closed under slot permutations, metric  *)
(* contractions, sums and constant multiples.                                *)
(* ------------------------------------------------------------------------- *)

let lbilin_RULES,lbilin_INDUCT,lbilin_CASES = new_inductive_definition
 `(!p q. lbilin (p + q) p q
           (\(G:real^N->real^N^N) (tf:real^N->(num->real^N)->real)
             (tg:real^N->(num->real^N)->real). ltprod p tf tg)) /\
  (!k p q s B. lbilin k p q B /\ s permutes 1..k
               ==> lbilin k p q (\G tf tg. ltperm s (B G tf tg))) /\
  (!k p q B. lbilin (k + 2) p q B
             ==> lbilin k p q (\G tf tg. ltcontr G (B G tf tg))) /\
  (!k p q B1 B2. lbilin k p q B1 /\ lbilin k p q B2
                 ==> lbilin k p q (\G tf tg y u. B1 G tf tg y u + B2 G tf tg y u)) /\
  (!k p q c B. lbilin k p q B
               ==> lbilin k p q (\G tf tg y u. c * B G tf tg y u))`;;


