let RFA_LTLAP_0 = prove
 (`!U (G:real^N->real^N^N) f y u.
        metric_field U G /\ smooth_map_on U (\x. lift(f x)) /\ y IN U
        ==> ltlap 0 G (\x u. f x) y u = llap G f y`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `open(U:real^N->bool)` ASSUME_TAC THENL
   [ASM_MESON_TAC[metric_field]; ALL_TAC] THEN
  MP_TAC(ISPECL [`U:real^N->bool`; `G:real^N->real^N^N`; `f:real^N->real`;
                 `y:real^N`] LRG_LLAP_LNABLA) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
  REWRITE_TAC[ltlap; RFA_LNABLA_ITER_2; ADD_CLAUSES] THEN
  SUBGOAL_THEN
   `lnabla 0 (G:real^N->real^N^N) (\x u. (f:real^N->real) x) =
    (\z u. drop(frechet_derivative (\w. lift(f w)) (at z) (u 1)))`
  SUBST1_TAC THENL
   [REWRITE_TAC[LRG_LNABLA_EQ; FUN_EQ_THM; ADD_CLAUSES] THEN
    REWRITE_TAC[SUM_CLAUSES_NUMSEG] THEN CONV_TAC NUM_REDUCE_CONV THEN
    REWRITE_TAC[REAL_SUB_RZERO];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ltensor_field 1 U
      (\z u. drop(frechet_derivative (\w. lift((f:real^N->real) w)) (at z) (u 1))) /\
    (!u. smooth_map_on U
           (\z. lift(drop(frechet_derivative (\w. lift((f:real^N->real) w))
                                             (at z) (u 1)))))`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`0`; `U:real^N->bool`; `G:real^N->real^N^N`;
                   `\x:real^N u:num->real^N. (f:real^N->real) x`]
           LNABLA_TENSOR_FIELD) THEN
    ANTS_TAC THENL
     [ASM_REWRITE_TAC[ltensor_field] THEN ARITH_TAC; ALL_TAC] THEN
    REWRITE_TAC[LRG_LNABLA_EQ; ADD_CLAUSES] THEN
    REWRITE_TAC[SUM_CLAUSES_NUMSEG] THEN CONV_TAC NUM_REDUCE_CONV THEN
    REWRITE_TAC[REAL_SUB_RZERO; ETA_AX];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`1`; `U:real^N->bool`; `G:real^N->real^N^N`;
     `\z u. drop(frechet_derivative (\w. lift((f:real^N->real) w)) (at z) (u 1))`]
     LNABLA_TENSOR_FIELD) THEN
  ASM_REWRITE_TAC[ltensor_field] THEN
  DISCH_THEN(MP_TAC o SPEC `y:real^N` o CONJUNCT1) THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN(LABEL_TAC "dep" o CONJUNCT1) THEN
