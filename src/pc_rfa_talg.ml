        metric_field U G /\ ltensor_field k U f /\ ltensor_field k U g /\ y IN U
        ==> ltnorm2 k G (\y u. f y u + g y u) y <=
            &2 * ltnorm2 k G f y + &2 * ltnorm2 k G g y`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`U:real^N->bool`; `G:real^N->real^N^N`; `y:real^N`]
         LRG_METRIC_INV_FACTOR) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(X_CHOOSE_THEN `S:real^N^N` STRIP_ASSUME_TAC) THEN
  MP_TAC(ISPECL [`k:num`; `U:real^N->bool`; `G:real^N->real^N^N`;
                 `\y u. (f:real^N->(num->real^N)->real) y u + g y u`;
                 `y:real^N`; `S:real^N^N`] LRG_LTNORM2_SQUARES) THEN
  MP_TAC(ISPECL [`k:num`; `U:real^N->bool`; `G:real^N->real^N^N`;
                 `g:real^N->(num->real^N)->real`;
                 `y:real^N`; `S:real^N^N`] LRG_LTNORM2_SQUARES) THEN
  MP_TAC(ISPECL [`k:num`; `U:real^N->bool`; `G:real^N->real^N^N`;
                 `f:real^N->(num->real^N)->real`;
                 `y:real^N`; `S:real^N^N`] LRG_LTNORM2_SQUARES) THEN
  ASM_SIMP_TAC[RFA_TENSOR_FIELD_ADD] THEN REPEAT(DISCH_THEN SUBST1_TAC) THEN
  REWRITE_TAC[GSYM SUM_LMUL; GSYM SUM_ADD_NUMSEG] THEN
  SIMP_TAC[GSYM SUM_ADD; LRG_INDEX_TUPLES_FINITE] THEN
  MATCH_MP_TAC SUM_LE THEN REWRITE_TAC[LRG_INDEX_TUPLES_FINITE] THEN
  REPEAT STRIP_TAC THEN BETA_TAC THEN
  REWRITE_TAC[REAL_ARITH `(a + b) pow 2 <= &2 * a pow 2 + &2 * b pow 2 <=>
                          &0 <= (a - b) pow 2`] THEN
  REWRITE_TAC[REAL_LE_POW_2]);;

let RFA_LBILIN_TENSOR = prove
