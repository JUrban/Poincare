(* ========================================================================= *)
(* Covariant derivatives of the generators: the product rule                 *)
(* for ltprod, and lnabla commuting with ltperm and ltcontr                  *)
(* (LRG_LNABLA_PERMUTE, LRG_LNABLA_CONTRACT of pc_lrg_evol).                 *)
(* ========================================================================= *)

let RFA_FRECHET_LIFT_MUL = prove
 (`!U (f:real^N->real) g y h.
        open U /\ smooth_map_on U (\z. lift(f z)) /\
        smooth_map_on U (\z. lift(g z)) /\ y IN U
        ==> drop(frechet_derivative (\z. lift(f z * g z)) (at y) h) =
            drop(frechet_derivative (\z. lift(f z)) (at y) h) * g y +
            f y * drop(frechet_derivative (\z. lift(g z)) (at y) h)`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `(\z. lift((f:real^N->real) z)) differentiable (at y) /\
                (\z. lift((g:real^N->real) z)) differentiable (at y)`
  STRIP_ASSUME_TAC THENL
   [CONJ_TAC THEN MATCH_MP_TAC SMOOTH_MAP_ON_DIFFERENTIABLE THEN
    EXISTS_TAC `U:real^N->bool` THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL
   [`f:real^N->real`;
    `\h. drop(frechet_derivative (\z. lift((f:real^N->real) z)) (at y) h)`;
    `\z. lift((g:real^N->real) z)`;
    `frechet_derivative (\z. lift((g:real^N->real) z)) (at y)`;
    `y:real^N`] HAS_DERIVATIVE_MUL_AT) THEN
  ANTS_TAC THENL
   [CONJ_TAC THENL
     [REWRITE_TAC[o_DEF; LIFT_DROP; ETA_AX] THEN
      ASM_REWRITE_TAC[GSYM FRECHET_DERIVATIVE_WORKS];
      ASM_REWRITE_TAC[GSYM FRECHET_DERIVATIVE_WORKS]];
    ALL_TAC] THEN
  REWRITE_TAC[GSYM LIFT_CMUL] THEN
  DISCH_THEN(MP_TAC o MATCH_MP FRECHET_DERIVATIVE_AT) THEN
  DISCH_THEN(fun th -> REWRITE_TAC[GSYM th]) THEN
  REWRITE_TAC[DROP_ADD; DROP_CMUL; LIFT_DROP] THEN REAL_ARITH_TAC);;

let RFA_LNABLA_LTPROD = prove
 (`!p q U (G:real^N->real^N^N) tf tg y u.
        metric_field U G /\ ltensor_field p U tf /\ ltensor_field q U tg /\
        (!u. smooth_map_on U (\x. lift(tf x u))) /\
        (!u. smooth_map_on U (\x. lift(tg x u))) /\ y IN U
        ==> lnabla (p + q) G (ltprod p tf tg) y u =
            lnabla p G tf y (\m. if m = p + 1 then u(p + q + 1) else u m) *
            tg y (\m. u(m + p)) +
            tf y u * lnabla q G tg y (\m. u(m + p))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `open(U:real^N->bool)` ASSUME_TAC THENL
   [ASM_MESON_TAC[metric_field]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!x w w'. x IN U /\ (!m. 1 <= m /\ m <= p ==> w m = w' m)
             ==> (tf:real^N->(num->real^N)->real) x w = tf x w'`
  (LABEL_TAC "fd") THENL
   [ASM_MESON_TAC[ltensor_field]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!x w w'. x IN U /\ (!m. 1 <= m /\ m <= q ==> w m = w' m)
             ==> (tg:real^N->(num->real^N)->real) x w = tg x w'`
  (LABEL_TAC "gd") THENL
   [ASM_MESON_TAC[ltensor_field]; ALL_TAC] THEN
  REWRITE_TAC[LRG_LNABLA_EQ; ltprod] THEN
  REWRITE_TAC[ARITH_RULE `(p + q) + 1 = p + q + 1`;
              ARITH_RULE `(q + 1) + p = p + q + 1`] THEN
  ABBREV_TAC `e:real^N = u(p + q + 1)` THEN
  ABBREV_TAC `gv = (tg:real^N->(num->real^N)->real) y (\m. u(m + p))` THEN
  ABBREV_TAC `fu = (tf:real^N->(num->real^N)->real) y u` THEN
  SUBGOAL_THEN
   `drop(frechet_derivative
          (\x. lift((tf:real^N->(num->real^N)->real) x u *
                    (tg:real^N->(num->real^N)->real) x (\m. u(m + p))))
          (at y) e) =
    drop(frechet_derivative (\x. lift(tf x u)) (at y) e) * gv +
    fu * drop(frechet_derivative (\x. lift(tg x (\m. u(m + p)))) (at y) e)`
  SUBST1_TAC THENL
   [MAP_EVERY EXPAND_TAC ["gv"; "fu"] THEN
    MATCH_MP_TAC RFA_FRECHET_LIFT_MUL THEN
    EXISTS_TAC `U:real^N->bool` THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `frechet_derivative (\x. lift((tf:real^N->(num->real^N)->real) x
                           (\m. if m = p + 1 then e else u m))) (at y) =
    frechet_derivative (\x. lift(tf x u)) (at y)`
  SUBST1_TAC THENL
   [MATCH_MP_TAC LRG_FRECHET_DERIVATIVE_EQ_OPEN THEN
    EXISTS_TAC `U:real^N->bool` THEN ASM_REWRITE_TAC[] THEN
    REPEAT STRIP_TAC THEN AP_TERM_TAC THEN USE_THEN "fd" MATCH_MP_TAC THEN
    ASM_REWRITE_TAC[] THEN REPEAT STRIP_TAC THEN
    SUBGOAL_THEN `~((m:num) = p + 1)` (fun th -> REWRITE_TAC[th]) THEN
    ASM_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN
   `sum(1..p + q)
      (\i. (tf:real^N->(num->real^N)->real) y
             (\j. if j = i then christoffel G y e (u i) else u j) *
           (tg:real^N->(num->real^N)->real) y
             (\m. if m + p = i then christoffel G y e (u i) else u(m + p))) =
    sum(1..p) (\i. tf y (\j. if j = i then christoffel G y e (u i) else u j)) * gv +
    fu * sum(1..q) (\i. tg y (\j. if j = i then christoffel G y e (u(i + p))
                                  else u(j + p)))`
  SUBST1_TAC THENL
   [SIMP_TAC[SUM_ADD_SPLIT; ARITH_RULE `1 <= p + 1`] THEN BINOP_TAC THENL
     [REWRITE_TAC[GSYM SUM_RMUL] THEN MATCH_MP_TAC SUM_EQ_NUMSEG THEN
      X_GEN_TAC `i:num` THEN STRIP_TAC THEN BETA_TAC THEN AP_TERM_TAC THEN
      EXPAND_TAC "gv" THEN USE_THEN "gd" MATCH_MP_TAC THEN
      ASM_REWRITE_TAC[] THEN REPEAT STRIP_TAC THEN BETA_TAC THEN
      SUBGOAL_THEN `~((m:num) + p = i)` (fun th -> REWRITE_TAC[th]) THEN
      ASM_ARITH_TAC;
      ALL_TAC] THEN
    ONCE_REWRITE_TAC[ADD_SYM] THEN REWRITE_TAC[SUM_OFFSET] THEN
    REWRITE_TAC[GSYM SUM_LMUL] THEN MATCH_MP_TAC SUM_EQ_NUMSEG THEN
    X_GEN_TAC `i:num` THEN STRIP_TAC THEN BETA_TAC THEN BINOP_TAC THENL
