    ASM_CASES_TAC `m = 2` THEN ASM_REWRITE_TAC[] THENL
     [COND_CASES_TAC THEN ASM_REWRITE_TAC[] THEN ASM_ARITH_TAC; ALL_TAC] THEN
    AP_THM_TAC THEN AP_THM_TAC THEN AP_TERM_TAC THEN ASM_ARITH_TAC;
    ALL_TAC] THEN
  USE_THEN "fl" MATCH_MP_TAC THEN ASM_ARITH_TAC);;

