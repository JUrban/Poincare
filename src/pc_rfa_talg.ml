let RFA_TENSOR_FIELD_ADD = prove
 (`!k U (f:real^N->(num->real^N)->real) g.
        ltensor_field k U f /\ ltensor_field k U g
        ==> ltensor_field k U (\y u. f y u + g y u)`,
  REWRITE_TAC[ltensor_field] THEN REPEAT STRIP_TAC THENL
   [BINOP_TAC THEN ASM_MESON_TAC[];
    REWRITE_TAC[LIFT_ADD] THEN MATCH_MP_TAC LINEAR_COMPOSE_ADD THEN
    ASM_MESON_TAC[]]);;

let RFA_TENSOR_FIELD_CMUL = prove
 (`!k U (f:real^N->(num->real^N)->real) c.
        ltensor_field k U f ==> ltensor_field k U (\y u. c * f y u)`,
  REWRITE_TAC[ltensor_field] THEN REPEAT STRIP_TAC THENL
   [AP_TERM_TAC THEN ASM_MESON_TAC[];
    REWRITE_TAC[LIFT_CMUL] THEN MATCH_MP_TAC LINEAR_COMPOSE_CMUL THEN
    ASM_MESON_TAC[]]);;

let RFA_LTNORM2_CMUL = prove
 (`!k (G:real^N->real^N^N) (f:real^N->(num->real^N)->real) c y.
        ltnorm2 k G (\y u. c * f y u) y = c pow 2 * ltnorm2 k G f y`,
  REWRITE_TAC[ltnorm2; GSYM SUM_LMUL] THEN REPEAT GEN_TAC THEN
  MATCH_MP_TAC SUM_EQ THEN GEN_TAC THEN DISCH_TAC THEN BETA_TAC THEN
  MATCH_MP_TAC SUM_EQ THEN GEN_TAC THEN DISCH_TAC THEN BETA_TAC THEN
  REWRITE_TAC[REAL_POW_2] THEN REAL_ARITH_TAC);;

let RFA_LTNORM2_ADD_LE = prove
