                 `f:real^N->(num->real^N)->real`; `g:real^N->(num->real^N)->real`;
                 `y:real^N`; `S:real^N^N`] RFA_LTINNER_SQUARES) THEN
  MP_TAC(ISPECL [`k:num`; `U:real^N->bool`; `G:real^N->real^N^N`;
