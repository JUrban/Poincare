let RFA_LINEAR_LIFT_MUL_CONST = prove
 (`!(f:real^N->real) c.
        linear (\v. lift(f v)) ==> linear (\v. lift(f v * c))`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `(\v:real^N. lift((f:real^N->real) v * c)) = (\v. c % lift(f v))`
  SUBST1_TAC THENL
   [REWRITE_TAC[FUN_EQ_THM; GSYM LIFT_CMUL] THEN REWRITE_TAC[REAL_MUL_SYM];
    MATCH_MP_TAC LINEAR_COMPOSE_CMUL THEN ASM_REWRITE_TAC[]]);;

let RFA_LINEAR_LIFT_CONST_MUL = prove
 (`!(f:real^N->real) c.
        linear (\v. lift(f v)) ==> linear (\v. lift(c * f v))`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[LIFT_CMUL] THEN
  MATCH_MP_TAC LINEAR_COMPOSE_CMUL THEN ASM_REWRITE_TAC[]);;

let RFA_LTPROD_FIELD = prove
 (`!p q U (tf:real^N->(num->real^N)->real) tg.
        ltensor_field p U tf /\ ltensor_field q U tg
        ==> ltensor_field (p + q) U (ltprod p tf tg)`,
  REPEAT GEN_TAC THEN REWRITE_TAC[ltensor_field; ltprod] THEN
  DISCH_THEN(CONJUNCTS_THEN2 (LABEL_TAC "f") (LABEL_TAC "g")) THEN
  X_GEN_TAC `y:real^N` THEN DISCH_TAC THEN
  REMOVE_THEN "f" (MP_TAC o SPEC `y:real^N`) THEN
  REMOVE_THEN "g" (MP_TAC o SPEC `y:real^N`) THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN(CONJUNCTS_THEN2 (LABEL_TAC "gd") (LABEL_TAC "gl")) THEN
  DISCH_THEN(CONJUNCTS_THEN2 (LABEL_TAC "fd") (LABEL_TAC "fl")) THEN
  CONJ_TAC THENL
   [REPEAT STRIP_TAC THEN BINOP_TAC THENL
     [USE_THEN "fd" MATCH_MP_TAC THEN REPEAT STRIP_TAC THEN
      FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_ARITH_TAC;
      USE_THEN "gd" MATCH_MP_TAC THEN REPEAT STRIP_TAC THEN BETA_TAC THEN
      FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_ARITH_TAC];
    ALL_TAC] THEN
  MAP_EVERY X_GEN_TAC [`i:num`; `u:num->real^N`] THEN STRIP_TAC THEN
  BETA_TAC THEN ASM_CASES_TAC `(i:num) <= p` THENL
   [SUBGOAL_THEN
     `!v:real^N. (tg:real^N->(num->real^N)->real) y
                   (\m. if m + p = i then v else u(m + p)) =
                 tg y (\m. u(m + p))`
     (fun th -> REWRITE_TAC[th]) THENL
     [GEN_TAC THEN USE_THEN "gd" MATCH_MP_TAC THEN REPEAT STRIP_TAC THEN
      BETA_TAC THEN SUBGOAL_THEN `~((m:num) + p = i)` (fun th -> REWRITE_TAC[th]) THEN
      ASM_ARITH_TAC;
      MATCH_MP_TAC RFA_LINEAR_LIFT_MUL_CONST THEN
      USE_THEN "fl" MATCH_MP_TAC THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!v:real^N. (tf:real^N->(num->real^N)->real) y
                 (\j. if j = i then v else u j) = tf y u`
   (fun th -> REWRITE_TAC[th]) THENL
   [GEN_TAC THEN USE_THEN "fd" MATCH_MP_TAC THEN REPEAT STRIP_TAC THEN
    BETA_TAC THEN SUBGOAL_THEN `~((m:num) = i)` (fun th -> REWRITE_TAC[th]) THEN
    ASM_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!v:real^N. (\m. if m + p = i then v else (u:num->real^N)(m + p)) =
               (\j. if j = i - p then v else (\m. u(m + p)) j)`
   (fun th -> REWRITE_TAC[th]) THENL
   [GEN_TAC THEN REWRITE_TAC[FUN_EQ_THM] THEN X_GEN_TAC `m:num` THEN
    BETA_TAC THEN AP_THM_TAC THEN AP_THM_TAC THEN AP_TERM_TAC THEN
    ASM_ARITH_TAC;
    ALL_TAC] THEN
  MATCH_MP_TAC RFA_LINEAR_LIFT_CONST_MUL THEN
  USE_THEN "gl" MATCH_MP_TAC THEN ASM_ARITH_TAC);;

