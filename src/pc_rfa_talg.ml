let RFA_SUM_CAUCHY_SCHWARZ = prove
 (`!(a:A->real) b s.
        FINITE s
        ==> sum s (\i. a i * b i) pow 2 <=
            sum s (\i. a i pow 2) * sum s (\i. b i pow 2)`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `&0 <= sum s (\i. sum s (\j. ((a:A->real) i * b j - a j * b i) pow 2))`
  MP_TAC THENL
   [MATCH_MP_TAC SUM_POS_LE THEN ASM_REWRITE_TAC[] THEN REPEAT STRIP_TAC THEN
    BETA_TAC THEN MATCH_MP_TAC SUM_POS_LE THEN ASM_REWRITE_TAC[REAL_LE_POW_2];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!i:A. sum s (\j. (a i * b j - a j * b i) pow 2) =
          a i pow 2 * sum s (\i. b i pow 2) + b i pow 2 * sum s (\i. a i pow 2) -
          &2 * (a i * b i) * sum s (\i. a i * b i)`
  (fun th -> REWRITE_TAC[th]) THENL
   [GEN_TAC THEN
    REWRITE_TAC[REAL_ARITH `(x * y - z * w) pow 2 =
                            x pow 2 * y pow 2 + w pow 2 * z pow 2 -
                            &2 * (x * w) * (z * y)`] THEN
    ASM_SIMP_TAC[SUM_SUB; SUM_ADD; SUM_LMUL];
    ALL_TAC] THEN
  ASM_SIMP_TAC[SUM_SUB; SUM_ADD; SUM_RMUL; SUM_LMUL] THEN
  REAL_ARITH_TAC);;

let RFA_SUM_PRODUCT_EXPAND = prove
 (`!(a:B->A->real) x z s t.
        FINITE s /\ FINITE t
        ==> sum t (\p. sum s (\i. a p i * x i) * sum s (\j. a p j * z j)) =
            sum s (\i. sum s (\j. x i * z j * sum t (\p. a p i * a p j)))`,
  REPEAT STRIP_TAC THEN
  REWRITE_TAC[GSYM SUM_RMUL] THEN REWRITE_TAC[GSYM SUM_LMUL] THEN
  GEN_REWRITE_TAC LAND_CONV
   [MATCH_MP SUM_SWAP (CONJ (ASSUME `FINITE(t:B->bool)`)
                            (ASSUME `FINITE(s:A->bool)`))] THEN
  MATCH_MP_TAC SUM_EQ THEN X_GEN_TAC `i:A` THEN DISCH_TAC THEN BETA_TAC THEN
  GEN_REWRITE_TAC LAND_CONV
   [MATCH_MP SUM_SWAP (CONJ (ASSUME `FINITE(t:B->bool)`)
                            (ASSUME `FINITE(s:A->bool)`))] THEN
  MATCH_MP_TAC SUM_EQ THEN X_GEN_TAC `j:A` THEN DISCH_TAC THEN BETA_TAC THEN
  MATCH_MP_TAC SUM_EQ THEN X_GEN_TAC `p:B` THEN DISCH_TAC THEN BETA_TAC THEN
  REAL_ARITH_TAC);;

let RFA_LTINNER_SQUARES = prove
 (`!k U (G:real^N->real^N^N) f g y (S:real^N^N).
        ltensor_field k U f /\ ltensor_field k U g /\ y IN U /\
        matrix_inv(G y) = transp S ** S
        ==> ltinner k G f g y =
            sum (index_tuples k (:N))
                (\p. f y (\m. transp S ** basis(p m)) *
                     g y (\m. transp S ** basis(p m)))`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `!(h:real^N->(num->real^N)->real) p.
        ltensor_field k U h /\ p IN index_tuples k (:N)
        ==> h y (\m. transp S ** basis(p m)) =
            sum (index_tuples k (:N))
                (\i. product (1..k) (\m. (S:real^N^N)$(p m)$(i m)) *
                     h y (\m. basis(i m)))`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`k:num`; `U:real^N->bool`; `h:real^N->(num->real^N)->real`;
                   `y:real^N`] LRG_TENSOR_FIELD_EXPAND) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN(fun th -> GEN_REWRITE_TAC LAND_CONV [th]) THEN
    MATCH_MP_TAC SUM_EQ THEN X_GEN_TAC `i:num->num` THEN DISCH_TAC THEN
    BETA_TAC THEN AP_THM_TAC THEN AP_TERM_TAC THEN
    MATCH_MP_TAC PRODUCT_EQ_NUMSEG THEN X_GEN_TAC `m:num` THEN STRIP_TAC THEN
    BETA_TAC THEN MATCH_MP_TAC LRG_TRANSP_BASIS_COMPONENT THEN
    MP_TAC(ISPECL [`p:num->num`; `k:num`; `m:num`] LRG_INDEX_TUPLES_RANGE) THEN
    MP_TAC(ISPECL [`i:num->num`; `k:num`; `m:num`] LRG_INDEX_TUPLES_RANGE) THEN
    ASM_REWRITE_TAC[] THEN ARITH_TAC;
    ALL_TAC] THEN
  MATCH_MP_TAC EQ_TRANS THEN
  EXISTS_TAC
   `sum (index_tuples k (:N))
     (\p. sum (index_tuples k (:N))
             (\i. product (1..k) (\m. (S:real^N^N)$(p m)$(i m)) *
                  (f:real^N->(num->real^N)->real) y (\m. basis(i m))) *
          sum (index_tuples k (:N))
             (\j. product (1..k) (\m. (S:real^N^N)$(p m)$(j m)) *
                  (g:real^N->(num->real^N)->real) y (\m. basis(j m))))` THEN
  CONJ_TAC THENL
   [ALL_TAC;
    MATCH_MP_TAC SUM_EQ THEN X_GEN_TAC `p:num->num` THEN DISCH_TAC THEN
    BETA_TAC THEN CONV_TAC SYM_CONV THEN BINOP_TAC THEN
    FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[]] THEN
  SIMP_TAC[RFA_SUM_PRODUCT_EXPAND; LRG_INDEX_TUPLES_FINITE] THEN
  REWRITE_TAC[ltinner] THEN ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC SUM_EQ THEN X_GEN_TAC `i:num->num` THEN DISCH_TAC THEN
  BETA_TAC THEN MATCH_MP_TAC SUM_EQ THEN X_GEN_TAC `j:num->num` THEN
  DISCH_TAC THEN BETA_TAC THEN AP_TERM_TAC THEN AP_TERM_TAC THEN
  MATCH_MP_TAC LRG_PRODUCT_TRANSP_MUL THEN ASM_REWRITE_TAC[]);;

let RFA_LTINNER_CAUCHY_SCHWARZ = prove
