let RFA_LTPERM_FIELD = prove
 (`!k s U (tf:real^N->(num->real^N)->real).
        s permutes 1..k /\ ltensor_field k U tf
        ==> ltensor_field k U (ltperm s tf)`,
  REPEAT GEN_TAC THEN REWRITE_TAC[ltensor_field; ltperm] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (LABEL_TAC "f")) THEN
  SUBGOAL_THEN `!m. 1 <= m /\ m <= k ==> 1 <= (s:num->num) m /\ s m <= k`
  (LABEL_TAC "range") THENL
   [GEN_TAC THEN DISCH_TAC THEN
    MP_TAC(ISPECL [`s:num->num`; `1..k`] PERMUTES_IMAGE) THEN
    ASM_REWRITE_TAC[] THEN REWRITE_TAC[EXTENSION; IN_IMAGE; IN_NUMSEG] THEN
    ASM_MESON_TAC[];
    ALL_TAC] THEN
  X_GEN_TAC `y:real^N` THEN DISCH_TAC THEN
  REMOVE_THEN "f" (MP_TAC o SPEC `y:real^N`) THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN(CONJUNCTS_THEN2 (LABEL_TAC "fd") (LABEL_TAC "fl")) THEN
  CONJ_TAC THENL
   [REPEAT STRIP_TAC THEN USE_THEN "fd" MATCH_MP_TAC THEN
    REPEAT STRIP_TAC THEN BETA_TAC THEN FIRST_X_ASSUM MATCH_MP_TAC THEN
    USE_THEN "range" MATCH_MP_TAC THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MAP_EVERY X_GEN_TAC [`i:num`; `u:num->real^N`] THEN STRIP_TAC THEN
  BETA_TAC THEN
  SUBGOAL_THEN
   `!v:real^N. (\m. if (s:num->num) m = i then v else (u:num->real^N)(s m)) =
               (\j. if j = inverse s i then v else (\m. u(s m)) j)`
   (fun th -> REWRITE_TAC[th]) THENL
   [GEN_TAC THEN REWRITE_TAC[FUN_EQ_THM] THEN X_GEN_TAC `m:num` THEN
    BETA_TAC THEN AP_THM_TAC THEN AP_THM_TAC THEN AP_TERM_TAC THEN
    ASM_MESON_TAC[PERMUTES_INVERSE_EQ];
    ALL_TAC] THEN
  USE_THEN "fl" MATCH_MP_TAC THEN
  MP_TAC(ISPECL [`inverse(s:num->num)`; `1..k`] PERMUTES_IMAGE) THEN
  ASM_SIMP_TAC[PERMUTES_INVERSE] THEN
  REWRITE_TAC[EXTENSION; IN_IMAGE; IN_NUMSEG] THEN ASM_MESON_TAC[]);;

