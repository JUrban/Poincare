  SUBGOAL_THEN `&0 <= ltnorm2 k (G:real^N->real^N^N) f y /\ &0 <= ltnorm2 k G g y`
  STRIP_ASSUME_TAC THENL [ASM_MESON_TAC[LTNORM2_POS]; ALL_TAC] THEN
  ASM_SIMP_TAC[GSYM SQRT_MUL] THEN
  GEN_REWRITE_TAC LAND_CONV [GSYM POW_2_SQRT_ABS] THEN
  MATCH_MP_TAC SQRT_MONO_LE THEN REWRITE_TAC[REAL_LE_POW_2] THEN
  MATCH_MP_TAC RFA_LTINNER_CAUCHY_SCHWARZ THEN EXISTS_TAC `U:real^N->bool` THEN
  ASM_REWRITE_TAC[]);;

let RFA_LNABLA_ITER_1 = prove
 (`!k (G:real^N->real^N^N) (tf:real^N->(num->real^N)->real).
