    STRIP_TAC THEN CONJ_TAC THENL [ASM_MESON_TAC[lbilin_RULES]; ALL_TAC] THEN
    EXISTS_TAC
     `\(G:real^N->real^N^N) (a1:real^N->(num->real^N)->real)
